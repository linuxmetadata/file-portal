const fs = require("fs");
const path = require("path");
const XLSX = require("xlsx");

const { readWorkbook: readExcel } = require("./excelReader");

/*
======================================================
SMART XLS READER
======================================================

Purpose:
- Preserve existing normal XLS processing.
- Detect HTML-based XLS files.
- Convert HTML tables into a normal SheetJS workbook.
- Return the same workbook structure expected by the
  existing validation pipeline.

IMPORTANT:
- Normal XLS files are NOT changed.
- XLSX files are NOT changed.
- Existing extractor / analyzer / matcher are NOT changed.
======================================================
*/

//======================================================
// CHECK WHETHER FILE LOOKS LIKE HTML
//======================================================

function looksLikeHTML(filePath) {

    try {

        const buffer = fs.readFileSync(filePath);

        if (!buffer || buffer.length === 0)
            return false;

        // Read only the beginning of the file.
        // HTML/XLS files generated by reporting systems
        // normally contain these markers near the beginning.
        const sample = buffer
            .subarray(0, Math.min(buffer.length, 1024 * 1024))
            .toString("utf8")
            .toLowerCase();

        return (

            sample.includes("<html") ||

            sample.includes("<!doctype html") ||

            sample.includes("<table") ||

            sample.includes("<tr") ||

            sample.includes("<td") ||

            sample.includes("<th")

        );

    }

    catch (error) {

        return false;

    }

}


//======================================================
// EXTRACT TABLES FROM HTML
//======================================================

function extractHTMLTables(html) {

    const tables = [];

    const tableRegex =
        /<table\b[^>]*>([\s\S]*?)<\/table>/gi;

    let tableMatch;

    while (
        (tableMatch = tableRegex.exec(html)) !== null
    ) {

        const tableHTML = tableMatch[1];

        const rows = [];

        const rowRegex =
            /<tr\b[^>]*>([\s\S]*?)<\/tr>/gi;

        let rowMatch;

        while (
            (rowMatch = rowRegex.exec(tableHTML)) !== null
        ) {

            const rowHTML = rowMatch[1];

            const cells = [];

            const cellRegex =
                /<(td|th)\b[^>]*>([\s\S]*?)<\/\1>/gi;

            let cellMatch;

            while (
                (cellMatch = cellRegex.exec(rowHTML)) !== null
            ) {

                let value =
                    cellMatch[2];

                // Remove scripts/styles
                value =
                    value.replace(
                        /<(script|style)\b[^>]*>[\s\S]*?<\/\1>/gi,
                        ""
                    );

                // Convert common HTML breaks
                value =
                    value.replace(
                        /<br\s*\/?>/gi,
                        " "
                    );

                // Remove remaining HTML tags
                value =
                    value.replace(
                        /<[^>]+>/g,
                        " "
                    );

                // Decode common HTML entities
                value =
                    decodeHTMLEntities(value);

                // Normalize whitespace
                value =
                    value
                        .replace(/\s+/g, " ")
                        .trim();

                cells.push(value);

            }

            if (cells.length > 0) {

                rows.push(cells);

            }

        }

        if (rows.length > 0) {

            tables.push(rows);

        }

    }

    return tables;

}


//======================================================
// HTML ENTITY DECODER
//======================================================

function decodeHTMLEntities(text) {

    return String(text || "")
        .replace(/&nbsp;/gi, " ")
        .replace(/&amp;/gi, "&")
        .replace(/&lt;/gi, "<")
        .replace(/&gt;/gi, ">")
        .replace(/&quot;/gi, '"')
        .replace(/&#39;/gi, "'")
        .replace(/&#x27;/gi, "'")
        .replace(/&#(\d+);/g, function (_, code) {

            try {

                return String.fromCharCode(
                    Number(code)
                );

            }

            catch (error) {

                return "";

            }

        });

}


//======================================================
// FIND BEST TABLE
//======================================================

function selectBestTable(tables) {

    if (!Array.isArray(tables) || tables.length === 0)
        return null;

    let bestTable = null;
    let bestScore = -1;

    for (const table of tables) {

        if (!Array.isArray(table))
            continue;

        let score = 0;

        for (const row of table) {

            if (!Array.isArray(row))
                continue;

            const text =
                row
                    .join(" ")
                    .toUpperCase();

            //--------------------------------------------------
            // Product table indicators
            //--------------------------------------------------

            if (
                text.includes("PRODUCT NAME") ||
                text.includes("PRODUCT") ||
                text.includes("OPENING") ||
                text.includes("PURCHASE") ||
                text.includes("SALE") ||
                text.includes("SALES") ||
                text.includes("CLOSING") ||
                text.includes("CLOSSTOCK")
            ) {

                score += 10;

            }

            //--------------------------------------------------
            // More columns generally means a report table
            //--------------------------------------------------

            if (row.length >= 5)
                score += 2;

        }

        //--------------------------------------------------
        // Prefer larger useful tables
        //--------------------------------------------------

        score += Math.min(
            table.length,
            100
        );

        if (score > bestScore) {

            bestScore = score;
            bestTable = table;

        }

    }

    return bestTable;

}


//======================================================
// READ HTML-BASED XLS
//======================================================

function readHTMLXLS(filePath) {

    try {

        const buffer =
            fs.readFileSync(filePath);

        const html =
            buffer.toString("utf8");

        const tables =
            extractHTMLTables(html);

        if (!tables.length) {

            return null;

        }

        const table =
            selectBestTable(tables);

        if (
            !table ||
            !Array.isArray(table) ||
            table.length === 0
        ) {

            return null;

        }

        //--------------------------------------------------
        // Convert HTML table into SheetJS workbook
        //--------------------------------------------------

        const worksheet =
            XLSX.utils.aoa_to_sheet(table);

        const workbook =
            XLSX.utils.book_new();

        XLSX.utils.book_append_sheet(
            workbook,
            worksheet,
            "Sheet1"
        );

        return workbook;

    }

    catch (error) {

        console.error(
            "HTML XLS Conversion Error:",
            error.message
        );

        return null;

    }

}


//======================================================
// MAIN SMART READER
//======================================================

function readWorkbook(filePath) {

    try {

        if (!filePath) {
            return null;
        }

        //--------------------------------------------------
        // IMPORTANT:
        // FIRST try the existing Excel reader.
        //
        // This MUST happen before HTML detection.
        //
        // Genuine XLS/XLSX files must keep their original
        // worksheets and structure.
        //--------------------------------------------------

        try {

            const excelResult = readExcel(filePath);

            //--------------------------------------------------
            // Existing reader returns:
            //
            // {
            //     success: true,
            //     workbook,
            //     message
            // }
            //--------------------------------------------------

            if (
                excelResult &&
                excelResult.success &&
                excelResult.workbook &&
                Array.isArray(excelResult.workbook.SheetNames) &&
                excelResult.workbook.SheetNames.length > 0
            ) {

                console.log(
                    "SMART XLS READER : Using existing Excel reader"
                );

                console.log(
                    "SMART XLS READER : Sheets =",
                    excelResult.workbook.SheetNames
                );

                return excelResult;

            }

        }

        catch (excelError) {

            console.log(
                "SMART XLS READER : Normal Excel read failed"
            );

            console.log(
                "SMART XLS READER :",
                excelError.message
            );

        }


        //--------------------------------------------------
        // ONLY AFTER NORMAL EXCEL READ FAILS
        // check whether the file is HTML-based XLS.
        //--------------------------------------------------

        if (looksLikeHTML(filePath)) {

            console.log(
                "SMART XLS READER : HTML-based XLS detected"
            );

            const htmlWorkbook =
                readHTMLXLS(filePath);

            if (htmlWorkbook) {

                console.log(
                    "SMART XLS READER : HTML table converted successfully"
                );

                console.log(
                    "SMART XLS READER : Sheets =",
                    htmlWorkbook.SheetNames
                );

                return {

                    success: true,

                    workbook: htmlWorkbook,

                    message:
                        "HTML-based XLS converted successfully."

                };

            }

            console.log(
                "SMART XLS READER : HTML conversion failed"
            );

        }


        //--------------------------------------------------
        // FINAL FALLBACK
        //--------------------------------------------------

        console.log(
            "SMART XLS READER : Excel reader final attempt"
        );

        return readExcel(filePath);

    }

    catch (error) {

        console.error(
            "SMART XLS READER ERROR:",
            error.message
        );

        //--------------------------------------------------
        // Final fallback to existing reader
        //--------------------------------------------------

        try {

            return readExcel(filePath);

        }

        catch (excelError) {

            console.error(
                "SMART XLS EXCEL FALLBACK ERROR:",
                excelError.message
            );

            return {

                success: false,

                workbook: null,

                message:
                    excelError.message

            };

        }

    }

}


